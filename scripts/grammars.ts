// Vendors the built-in tree-sitter grammars (ADR 0001) into src/analysis/structural/grammars/.
// Usage: node scripts/grammars.ts
//
// The pins are the `package`, `version` and `file` fields of grammars/manifest.json. For each
// package this downloads the published npm tarball (`npm pack`, which checks the registry's
// integrity hash), copies the `.wasm` and the licence file, and records the tarball integrity,
// the `.wasm` sha256 and the licence in the manifest. A pin whose recorded integrity no longer
// matches the registry fails. Rerunning with unchanged pins must leave the directory unchanged.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { GrammarManifest } from '../src/analysis/structural/languages.ts';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const grammarsDir = join(root, 'src', 'analysis', 'structural', 'grammars');
const manifestPath = join(grammarsDir, 'manifest.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as GrammarManifest;

const engine = JSON.parse(
  readFileSync(join(root, 'node_modules', 'web-tree-sitter', 'package.json'), 'utf8'),
) as { version: string };

const work = mkdtempSync(join(tmpdir(), 'bcr-grammars-'));
try {
  const specs = [...new Set(manifest.grammars.map((g) => `${g.package}@${g.version}`))];
  for (const spec of specs) {
    const entries = manifest.grammars.filter((g) => `${g.package}@${g.version}` === spec);
    const dest = mkdtempSync(join(work, 'pkg-'));
    const [packed] = JSON.parse(
      execFileSync('npm', ['pack', spec, '--json', '--silent', '--pack-destination', dest], {
        encoding: 'utf8',
        shell: process.platform === 'win32',
      }),
    ) as { filename: string; integrity: string }[];
    if (!packed) throw new Error(`npm pack ${spec} returned nothing`);
    // Relative file name and cwd, so Windows drive letters never reach tar.
    execFileSync('tar', ['-xzf', packed.filename], { cwd: dest });
    const pkgDir = join(dest, 'package');
    const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')) as {
      license: string;
      repository?: string | { url: string };
    };

    const licenseFile = `${entries[0]!.package}.LICENSE`;
    copyFileSync(join(pkgDir, 'LICENSE'), join(grammarsDir, licenseFile));
    for (const entry of entries) {
      if (entry.integrity && entry.integrity !== packed.integrity) {
        throw new Error(`${spec}: registry integrity changed (${packed.integrity})`);
      }
      copyFileSync(join(pkgDir, entry.file), join(grammarsDir, entry.file));
      entry.integrity = packed.integrity;
      entry.license = pkg.license;
      entry.repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
      entry.licenseFile = licenseFile;
      entry.sha256 = createHash('sha256')
        .update(readFileSync(join(grammarsDir, entry.file)))
        .digest('hex');
    }
    console.log(`Vendored ${spec} (${pkg.license})`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

const out: GrammarManifest = {
  $comment:
    'Generated by scripts/grammars.ts. To change a pin, edit package/version/file and run `npm run grammars`.',
  engine: `web-tree-sitter@${engine.version}`,
  grammars: manifest.grammars,
};
writeFileSync(manifestPath, `${JSON.stringify(out, null, 2)}\n`);
console.log(`Wrote ${manifestPath}`);
