// Checks production dependency licences against ADR 0002 and writes THIRD_PARTY_NOTICES.
// Usage: node scripts/licenses.ts [--out <file>]
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { init, type ModuleInfos } from 'license-checker-rseidelsohn';
import type { GrammarManifest } from '../src/analysis/structural/languages.ts';
import { evaluate, type DependencyLicense, type LicensePolicy } from './license-policy.ts';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const { values } = parseArgs({ options: { out: { type: 'string' } } });
const outFile = values.out ?? join(root, 'THIRD_PARTY_NOTICES');

const policy = JSON.parse(
  readFileSync(join(root, 'scripts', 'license-policy.json'), 'utf8'),
) as LicensePolicy;

const modules = await new Promise<ModuleInfos>((resolve, reject) => {
  init({ start: root, production: true, excludePrivatePackages: true }, (err, result) =>
    err ? reject(err) : resolve(result),
  );
});

interface Dependency extends DependencyLicense {
  repository?: string | undefined;
  licenseFile?: string | undefined;
}

const deps: Dependency[] = Object.entries(modules).map(([id, info]) => {
  const at = id.lastIndexOf('@');
  return {
    name: id.slice(0, at),
    version: id.slice(at + 1),
    licenses: [info.licenses ?? []].flat(),
    repository: info.repository,
    licenseFile: info.licenseFile,
  };
});

// Vendored grammar .wasm files (ADR 0001) are distributed too, but are not npm dependencies.
const grammarsDir = join(root, 'src', 'analysis', 'structural', 'grammars');
const grammars = JSON.parse(
  readFileSync(join(grammarsDir, 'manifest.json'), 'utf8'),
) as GrammarManifest;
const vendored = new Set<string>();
for (const g of grammars.grammars) {
  if (vendored.has(`${g.package}@${g.version}`)) continue;
  vendored.add(`${g.package}@${g.version}`);
  deps.push({
    name: g.package,
    version: g.version,
    licenses: g.license ? [g.license] : [],
    repository: g.repository,
    licenseFile: g.licenseFile && join(grammarsDir, g.licenseFile),
  });
}

const failures = deps.flatMap((dep) => {
  const verdict = evaluate(dep, policy);
  return verdict.ok ? [] : [`${dep.name}@${dep.version}: ${verdict.reason}`];
});
if (failures.length > 0) {
  console.error('Dependency licence check failed (policy: docs/adr/0002-project-license.md):');
  for (const f of failures) console.error(`  ${f}`);
  process.exit(1);
}

function licenseText(dep: Dependency): string {
  // license-checker falls back to a README when there is no licence file; don't paste READMEs.
  if (!dep.licenseFile || /^readme/i.test(basename(dep.licenseFile))) {
    return `(No licence file found. Licence: ${dep.licenses.join(', ')})`;
  }
  return readFileSync(dep.licenseFile, 'utf8').trim();
}

const header = `THIRD-PARTY SOFTWARE NOTICES

This file lists the third-party packages distributed with better-code-review and
their licence texts. It is generated by scripts/licenses.ts; do not edit it by hand.
`;
const sections = deps.map((dep) =>
  [
    '-'.repeat(80),
    `${dep.name}@${dep.version}`,
    `License: ${dep.licenses.join(', ')}`,
    ...(dep.repository ? [`Repository: ${dep.repository}`] : []),
    '',
    licenseText(dep),
  ].join('\n'),
);
const body =
  sections.length > 0 ? sections.join('\n\n') : 'No third-party packages are distributed.';
writeFileSync(outFile, `${header}\n${body}\n`);

console.log(`Licence check passed for ${deps.length} production dependencies. Wrote ${outFile}`);
